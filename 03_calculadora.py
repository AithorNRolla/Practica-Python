num1=input("Introduce primer número: ")
num2=input("Introduce segundo número: ")
#convertir de texto a números
num1=int(num1)
num2=int(num2)
suma=num1+num2
print(f"La suma del número {num1} y {num2} es: {suma} ")
resta=num1-num2
print(f"La resta del número {num1} y {num2} es:{resta}")
multiplicar=num1*num2
dividir=num1/num2
potencia=num1**num2
print(f"La multiplicación del número {num1} y {num2} es: {multiplicar} ")
print(f"La división del número {num1} y {num2} es: {dividir} ")
print(f"La potencia de los números {num1} y {num2} es: {potencia} ")
